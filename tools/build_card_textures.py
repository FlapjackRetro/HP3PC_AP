#!/usr/bin/env python3
"""Write mod/OpenCastle/wc_textures.h: each wizard card class's face texture (its default Skins[0]) from the
game's HGame.u, by card index in WizardCardManager.Cards (= the apworld's card order, items._CARDS).

Usage: python tools/build_card_textures.py <game_dir>     (game_dir holds system/HGame.u)
"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from ue2 import Package, load, Reader

p = Package(os.path.join(sys.argv[1], 'system', 'HGame.u'))
skin = {}
for e in p.exports:
    if p.objclass(e['idx']) != 'Class' or not e['name'].lower().startswith('wc_'):
        continue
    for nm, i, t, v in load(p, e['idx']).get('defaults', []):
        if nm == 'Skins':
            r = Reader(v[1]); n = r.ci(); refs = [r.ci() for _ in range(n)]
            if refs:
                skin[e['name'].lower()] = p.path(refs[0])
src = open(os.path.join(ROOT, 'apworld', 'hp3pc', 'items.py'), encoding='utf-8').read()
cards = re.findall(r'\(\s*(\d+), "([^"]+)", "([^"]+)"\)', src)
rows = []
for idx, cls, name in cards:
    tex = skin.get(cls.lower())
    if not tex:
        sys.exit(f'{cls}: no Skins in HGame.u')
    rows.append(f'    L"{tex}",   /* {idx} {name} */')
out = os.path.join(ROOT, 'mod', 'OpenCastle', 'wc_textures.h')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/build_card_textures.py from HGame.u: each wizard card\'s face texture (the card class\'s\n'
            '   default Skins[0]), by its index in WizardCardManager.Cards. */\n')
    f.write('static const wchar *const WC_TEXTURES[] = {\n' + '\n'.join(rows) + '\n};\n')
    f.write('#define NWC_TEXTURES (int)(sizeof WC_TEXTURES / sizeof WC_TEXTURES[0])\n')
print(len(rows), 'cards ->', os.path.relpath(out, ROOT))
