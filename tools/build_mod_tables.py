#!/usr/bin/env python3
"""Write mod/OpenCastle/aptables.h from the apworld's item and location tables, so the mod and the apworld can never
disagree on an ID. Run after tools/build_apworld_locations.py (or any change to items.py).

Usage: python tools/build_mod_tables.py      (from the repo root; needs no Archipelago install)
"""
import enum, importlib.util, os, sys, types

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORLD = os.path.join(ROOT, 'apworld', 'hp3pc')
OUT = os.path.join(ROOT, 'mod', 'OpenCastle', 'aptables.h')

# a stand-in BaseClasses, enough for items.py to import
bc = types.ModuleType('BaseClasses')
class IC(enum.IntFlag):
    filler = 0; progression = 1; useful = 2; trap = 4; skip_balancing = 8; deprioritized = 16
    progression_skip_balancing = 9
bc.ItemClassification = IC
bc.Item = object
sys.modules['BaseClasses'] = bc
pkg = types.ModuleType('hp3pc'); pkg.__path__ = [WORLD]; sys.modules['hp3pc'] = pkg


def load(name):
    spec = importlib.util.spec_from_file_location(f'hp3pc.{name}', os.path.join(WORLD, name + '.py'))
    m = importlib.util.module_from_spec(spec); sys.modules[f'hp3pc.{name}'] = m; spec.loader.exec_module(m)
    return m


items = load('items')
lt = load('location_table')

# item name -> what the mod does with it
SPELL_KEY = {'Alohomora': 'Alohomora', 'Depulso': 'Depulso', 'Lumos': 'Lumos', 'Rictusempra': 'Rictusempra',
             'Spongify': 'Spongify', 'Expecto Patronum': 'ExpectoPatronum', 'Carpe Retractum': 'CarpeRetractum',
             'Draconifors': 'Draconifors', 'Lapifors': 'Lapifors', 'Glacius': 'Glacius'}
DOOR_KEY = {'Carpe Retractum Challenge Unlock': 'ChCarpe', 'Draconifors Challenge Unlock': 'ChDracLap',
            'Glacius Challenge Unlock': 'ChGlacius', 'Hogwarts Express Unlock': 'Express',
            'Patronus Lesson Unlock': 'DADA', 'Library Unlock': 'Library', 'Shrieking Shack Unlock': 'Shack',
            'Paddock Unlock': 'Paddock', 'Monster Book Challenge Unlock': 'MonsterBook',
            'Hippogriff Challenge Unlock': 'Hippogriff', 'Doxy Challenge Unlock': 'Doxy', 'Bonus Room Unlock': 'BonusRoom',
            "Ron's Final Exam Unlock": 'ExamRon', "Hermione's Final Exam Unlock": 'ExamHermione',
            "Harry's Final Exam Unlock": 'ExamHarry'}


def w(s):
    return 'L"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"' if s else '0'


rows = []
for name, data in items.ITEM_TABLE.items():
    off = data.offset
    g1 = g2 = ''
    if name in SPELL_KEY:
        kind, key = 's', SPELL_KEY[name]
    elif name in DOOR_KEY:
        kind, key = 'd', DOOR_KEY[name]
        grants = [SPELL_KEY[s] for s in items.CHALLENGE_GRANTS.get(name, ())]
        g1, g2 = (grants + ['', ''])[:2]
    elif name.startswith('Portrait Password '):
        kind, key = 'w', 'Portrait' + name.rsplit(' ', 1)[1]
    elif name == 'Shortcut Passwords':
        kind, key = 'i', 'ShortcutPasswords'
    elif name == "Marauder's Map":
        kind, key = 'i', 'MaraudersMap'
    elif name in items.CURRENCY_VALUE:
        kind, key = 'c', ''
    elif name == 'Chocolate Frog':
        kind, key = 'f', ''
    elif name in items.CARD_CLASS:
        kind, key = 'k', items.CARD_CLASS[name]
    else:
        sys.exit(f'item {name!r}: no mod action')
    p, c = items.CURRENCY_VALUE.get(name, (0, 0))
    rows.append(f'    {{ {off}, \'{kind}\', {w(key)}, {p}, {c}, {w(g1)}, {w(g2)}, {w(name)} }},')

KIND = {'placed': 'P', 'container': 'C', 'event': 'E', 'secret': 'S', 'card': 'K', 'shop': 'H', 'vendor': 'V',
        'minigame': 'M'}
lrows = []
for loc in lt.LOCATIONS:
    lrows.append(f'    {{ {loc.offset}, \'{KIND[loc.kind]}\', {w(loc.map)}, {w(loc.actor)}, {w(loc.save_key)}, {w(loc.name)} }},')

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/build_mod_tables.py from apworld/hp3pc (items.py, location_table.py). Do not edit. */\n')
    f.write(f'#define AP_BASE_ID {items.BASE_ID}\n\n')
    f.write('/* kind: s spell, d door / level unlock (g1 / g2: spells it grants while split_challenge_spells is off),\n'
            '   w portrait password, i item flag (OC_Items_<key>), c currency (p pasties, c cakes), f chocolate frog,\n'
            '   k wizard card (key = card class) */\n')
    f.write('struct apitem { unsigned short off; char kind; const wchar *key; unsigned char p, c; const wchar *g1, *g2, *name; };\n')
    f.write('static const struct apitem AP_ITEMS[] = {\n' + '\n'.join(rows) + '\n};\n')
    f.write('#define AP_NITEMS (int)(sizeof AP_ITEMS / sizeof AP_ITEMS[0])\n\n')
    f.write('/* kind: P placed pasty / cake, C container, E event spawn, S secret area, K card (placed or event), H Fred &\n'
            '   George\'s shop, V student vendor purchase (actor vendor_<n>), M minigame reward (actor WinCard<n>) */\n')
    f.write('struct aploc { unsigned short off; char kind; const wchar *map, *actor, *key, *name; };\n')
    f.write('static const struct aploc AP_LOCS[] = {\n' + '\n'.join(lrows) + '\n};\n')
    f.write('#define AP_NLOCS (int)(sizeof AP_LOCS / sizeof AP_LOCS[0])\n')
print(f'{len(rows)} items, {len(lrows)} locations -> {os.path.relpath(OUT, ROOT)}')
